#      북(0)    
# 서(3)     동(1)  
#      남(2)
# 왼쪽 방향으로 rotation
# 0 -> 3 // 3 -> 2 // 2 -> 1 // 1 -> 0
# 왼쪽방향으로 rotate한 인덱스는 (기존인덱스 + 3) % 4로 구함 
def get_d_index_when_rotate_to_left(d):
    return (d + 3) % 4

# 0 -> 2 // 3 -> 1 // 2 -> 0 // 1 -> 3
# 후진한 인덱스는 (기존인덱스 + 2) % 4
def get_d_index_when_go_back(d):
    return (d + 2) % 4


def get_count_of_departments_cleaned_by_robot_vacuum(r, c, d, room_map):
    #       r  c
    # 북 : -1  0
    # 동 :  0  1
    # 남 :  1  0
    # 서 :  0 -1
    dr = [-1, 0, 1, 0]
    dc = [0, 1, 0, -1]
    n = len(room_map)
    m = len(room_map[0])
    count_of_departments_cleaned = 1
    room_map[r][c] = 2
    queue = deque([
        [r, c, d]
        ])
    while queue:
        r, c, d = queue.popleft()
        temp_d = d
        for i in range(4):
            temp_d = get_d_index_when_rotate_to_left(temp_d) # 북 -> 서
            new_r, new_c = r + dr[temp_d], c + dc[temp_d]
            if 0 <= new_r < n and 0 <= new_c < m and room_map[new_r][new_c] == 0:
                count_of_departments_cleaned += 1
                room_map[new_r][new_c] = 2
                queue.append([new_r, new_c, temp_d])
                break
            elif i == 3: # 네 방향 모두 청소가 이미 되어있거나 벽인 경우
                back_d = get_d_index_when_go_back(d)
                new_r, new_c = r + dr[back_d], c + dc[back_d]
                queue.append([new_r, new_c, d])

                if room_map[new_r][new_c] == 1:
                    return count_of_departments_cleaned
